#!/usr/bin/env python3
"""
pcf2c.py FONT.pcf[.gz] NAME > font_NAME.h

Converts the printable ASCII glyphs (32..126) of a fixed-width X11 PCF
bitmap font into a C table: one byte per pixel row, the leftmost pixel in
bit 7.  Used once to generate src/font6x10.h from the X.Org misc font
6x10-ISO8859-1 (public domain); the generated header is committed, so
building ucas does not need this script or the font.
"""
import gzip
import struct
import sys

PCF_METRICS = 1 << 2
PCF_BITMAPS = 1 << 3
PCF_BDF_ENCODINGS = 1 << 5
PCF_COMPRESSED_METRICS = 0x100


def load(path):
    data = open(path, "rb").read()
    if path.endswith(".gz"):
        data = gzip.decompress(data)
    if data[:4] != b"\x01fcp":
        sys.exit("not a PCF font")
    (ntab,) = struct.unpack_from("<i", data, 4)
    toc = {}
    for i in range(ntab):
        typ, fmt, size, off = struct.unpack_from("<iiii", data, 8 + 16 * i)
        toc[typ] = (fmt, size, off)
    return data, toc


def table(data, toc, typ):
    fmt, size, off = toc[typ]
    (fmt,) = struct.unpack_from("<i", data, off)
    big = ">" if fmt & 4 else "<"
    return fmt, big, off + 4


def main():
    path, name = sys.argv[1], sys.argv[2]
    data, toc = load(path)

    fmt, e, p = table(data, toc, PCF_METRICS)
    metrics = []
    if fmt & PCF_COMPRESSED_METRICS:
        (n,) = struct.unpack_from(e + "h", data, p)
        p += 2
        for i in range(n):
            lb, rb, w, asc, desc = (b - 0x80 for b in data[p:p + 5])
            metrics.append((lb, rb, w, asc, desc))
            p += 5
    else:
        (n,) = struct.unpack_from(e + "i", data, p)
        p += 4
        for i in range(n):
            lb, rb, w, asc, desc, _ = struct.unpack_from(e + "hhhhhH", data, p)
            metrics.append((lb, rb, w, asc, desc))
            p += 12

    fmt, e, p = table(data, toc, PCF_BITMAPS)
    (n,) = struct.unpack_from(e + "i", data, p)
    p += 4
    offsets = struct.unpack_from(e + "%di" % n, data, p)
    p += 4 * n + 16
    pad = 1 << (fmt & 3)
    msbit = bool(fmt & 8)
    if (fmt >> 4) & 3:
        sys.exit("scan units other than bytes are not handled")
    bits = data[p:]

    fmt, e, p = table(data, toc, PCF_BDF_ENCODINGS)
    min2, max2, min1, max1, dflt = struct.unpack_from(e + "hhhhh", data, p)
    p += 10
    count = (max2 - min2 + 1) * (max1 - min1 + 1)
    enc = struct.unpack_from(e + "%dH" % count, data, p)

    ascent = max(m[3] for m in metrics)
    descent = max(m[4] for m in metrics)
    height = ascent + descent
    width = max(m[2] for m in metrics)
    if width > 8:
        sys.exit("glyphs wider than 8 pixels are not handled")

    rows_all = []
    for ch in range(32, 127):
        g = enc[ch - min2] if min1 == 0 and min2 <= ch <= max2 else 0xFFFF
        rows = [0] * height
        if g != 0xFFFF:
            lb, rb, w, asc, desc = metrics[g]
            gw = rb - lb
            stride = ((gw + 7) // 8 + pad - 1) // pad * pad
            for r in range(asc + desc):
                v = 0
                for c in range(gw):
                    byte = bits[offsets[g] + r * stride + c // 8]
                    bit = (byte >> (7 - c % 8)) & 1 if msbit else \
                        (byte >> (c % 8)) & 1
                    if bit and 0 <= lb + c < 8:
                        v |= 0x80 >> (lb + c)
                y = ascent - asc + r
                if 0 <= y < height:
                    rows[y] = v
        rows_all.append(rows)

    print("/* generated by tools/pcf2c.py from %s; do not edit */" %
          path.split("/")[-1])
    print("#define FONT_%s_W %d" % (name.upper(), width))
    print("#define FONT_%s_H %d" % (name.upper(), height))
    print("static const unsigned char font_%s[95][%d] = {" % (name, height))
    for i, rows in enumerate(rows_all):
        print("\t{%s},\t/* %r */" % (", ".join("0x%02x" % r for r in rows),
                                     chr(32 + i)))
    print("};")


main()
